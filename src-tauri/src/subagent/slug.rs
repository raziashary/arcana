// Subagent slug generator.
//
// Format:  subagent-{parent_slug}-{epoch_millis}-{seq}
// Example: subagent-worker-backend-1745740800123-1
//
// The `subagent-` prefix is reserved by convention so cleanup logic can
// distinguish ephemeral subagents from persistent fleet agents. See
// `SubagentManager::cleanup_orphans` and the AgentCreate body in
// `bridge.rs`.
//
// Uniqueness guarantees:
//   - epoch_millis component → uniqueness across most spawns
//   - atomic seq counter     → uniqueness within the same millisecond
//   - process restart safe   → millis component changes monotonically

use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

/// Reserved prefix. Anything matching this prefix is considered ephemeral.
pub const SUBAGENT_PREFIX: &str = "subagent-";

static SEQ: AtomicU64 = AtomicU64::new(1);

/// Generate a unique subagent slug.
///
/// `parent_slug` is sanitised to `[a-z0-9-]` to avoid breaking core-orchestrator's
/// agent_id slugification rules. Empty parent_slug becomes "anon".
pub fn generate(parent_slug: &str) -> String {
    let parent = sanitise(parent_slug);
    let parent = if parent.is_empty() { "anon".to_string() } else { parent };

    let millis = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0);

    let seq = SEQ.fetch_add(1, Ordering::Relaxed);

    format!("{SUBAGENT_PREFIX}{parent}-{millis}-{seq}")
}

/// True iff the slug was generated by this module (or matches the convention
/// of being a subagent). Used by orphan cleanup to filter persistent fleet
/// agents away from ephemeral ones.
pub fn is_subagent_slug(slug: &str) -> bool {
    slug.starts_with(SUBAGENT_PREFIX)
}

/// Lowercase alphanumerics and hyphens. Anything else becomes a hyphen.
/// Consecutive hyphens collapse to one. Leading/trailing hyphens removed.
fn sanitise(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut last_hyphen = true; // suppresses leading hyphens
    for ch in s.chars() {
        let c = ch.to_ascii_lowercase();
        if c.is_ascii_alphanumeric() {
            out.push(c);
            last_hyphen = false;
        } else if !last_hyphen {
            out.push('-');
            last_hyphen = true;
        }
    }
    while out.ends_with('-') { out.pop(); }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unique_slugs_within_same_millisecond() {
        let a = generate("worker-backend");
        let b = generate("worker-backend");
        assert_ne!(a, b, "atomic seq must disambiguate");
    }

    #[test]
    fn prefix_check() {
        let s = generate("pa");
        assert!(is_subagent_slug(&s));
        assert!(!is_subagent_slug("worker-backend"));
        assert!(!is_subagent_slug("supervisor"));
    }

    #[test]
    fn sanitises_funky_parent() {
        let s = generate("Worker Backend!");
        assert!(s.starts_with("subagent-worker-backend-"), "got {s}");
    }

    #[test]
    fn handles_empty_parent() {
        let s = generate("");
        assert!(s.starts_with("subagent-anon-"), "got {s}");
    }
}
